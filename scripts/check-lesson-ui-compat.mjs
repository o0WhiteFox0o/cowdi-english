// Chạy bài golden qua đúng logic của LessonDetailPage hiện tại (chọn bước, Nghe câu, Nói theo,
// ReadingPassage, generateQuizFromLesson ×200) để biết nội dung v2 có hiện ra cho người học không.
//   node scripts/check-lesson-ui-compat.mjs
// Kết quả ngày 24/11/2026 ghi trong docs/05-implementation/content/MAP-CURRENT-UI.md.
import fs from 'fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const imp = (p) => import(pathToFileURL(path.join(root, p)).href);
const { GOLDEN_LESSONS } = await imp('src/data/lessons/_golden/index.js');
const { toLegacyShape } = await imp('src/data/lessons/schema.js');
const { withStandards } = await imp('src/data/lessons/standards.js');
const { withReading } = await imp('src/data/lessons/reading.js');
const src=fs.readFileSync(path.join(root,'src/features/lesson/LessonDetailPage.jsx'),'utf8');
const grab=(name)=>{const i=src.indexOf(`function ${name}(`); let d=0,j=src.indexOf('{',i); for(let k=j;k<src.length;k++){if(src[k]==='{')d++; else if(src[k]==='}'){d--; if(!d) return src.slice(i,k+1);}}};
const STEPS_SRC=src.slice(src.indexOf('const LESSON_STEPS'), src.indexOf('];', src.indexOf('const LESSON_STEPS'))+2);
const { generateQuizFromLesson, LESSON_STEPS } = new Function(`${grab('shuffleArray')}\n${grab('generateQuizFromLesson')}\n${STEPS_SRC}\nreturn {generateQuizFromLesson, LESSON_STEPS};`)();
for (const raw of GOLDEN_LESSONS) {
  const [lesson] = withReading(withStandards([toLegacyShape(raw)]));
  const r=[]; const ok=(c,m)=>r.push(`${c?'✓':'✗'} ${m}`);
  // steps (copy of LessonDetailPage logic)
  const hasListen=(lesson.grammar||[]).some(g=>(g.examples||[]).some(ex=>ex.en&&ex.vi&&ex.en.trim().split(/\s+/).length>=2));
  const steps=LESSON_STEPS.filter(s=>{ if(s.key==='grammar')return (lesson.grammar||[]).length>0; if(s.key==='reading')return !!lesson.reading?.passage; if(s.key==='listen')return hasListen; if(s.key==='quiz')return (lesson.quiz||[]).length>0; return true;}).map(s=>s.key);
  ok(steps.includes('quiz'), `các bước hiện: ${steps.join(' → ')}`);
  // speakSentences + listenPool
  let speakN=0, listenN=0, crash=null;
  try { speakN=[...lesson.vocabulary.map(v=>({en:v.example,vi:v.meaning})), ...lesson.grammar.flatMap(g=>g.examples.map(ex=>({en:ex.en,vi:ex.vi})))].filter(s=>s.en&&s.vi).length;
        listenN=new Set(lesson.grammar.flatMap(g=>g.examples.filter(ex=>ex.en&&ex.vi&&ex.en.trim().split(/\s+/).length>=2).map(ex=>ex.en.trim().toLowerCase()))).size; } catch(e){crash=e.message}
  ok(!crash, `Nói theo: ${speakN} câu · Nghe câu: ${listenN} câu ${crash||''}`);
  // reading
  const rd=lesson.reading; const tokens=rd.passage.match(/[A-Za-zÀ-ỹ']+|\s+|[^\sA-Za-zÀ-ỹ']/g)||[]; const hs=new Set(rd.highlights.map(w=>w.toLowerCase()));
  const vm=new Set(lesson.vocabulary.map(v=>v.word.toLowerCase())); const shown=[...new Set(tokens.filter(t=>hs.has(t.toLowerCase())).map(t=>t.toLowerCase()))];
  const clickable=shown.filter(t=>vm.has(t));
  ok(!rd.autoGenerated, `Đoạn văn: ${rd.autoGenerated?'TỰ GHÉP':'viết tay'}, tô ${shown.length} từ, bấm xem nghĩa được ${clickable.length}; có dịch: ${!!rd.translation}; câu hỏi hiểu bài: ${rd.questions.length}`);
  ok(!rd.passage.includes('\n'), `Xuống dòng/đoạn: ${rd.passage.includes('\n')?'UI gộp thành 1 khối (thiếu white-space: pre-line)':'không có'}`);
  // quiz runs
  const runs=[...Array(200)].map(()=>generateQuizFromLesson(lesson));
  const avgLen=runs.reduce((a,q)=>a+q.length,0)/runs.length; const avgOrig=runs.reduce((a,q)=>a+q.filter(x=>x._type==='original').length,0)/runs.length;
  const withEx=runs.reduce((a,q)=>a+q.filter(x=>x.explanation).length,0)/runs.length;
  ok(avgOrig>=lesson.quiz.length*0.8, `Quiz thực tế: ${avgLen.toFixed(1)} câu, trong đó câu soạn tay ${avgOrig.toFixed(1)}/${lesson.quiz.length}, có giải thích ${withEx.toFixed(1)} (UI không hiện)`);
  const uniqueEx=rd.examQuestions?.length; if(uniqueEx) ok(false, `Câu hỏi đề thi: ${rd.questions.length}/${uniqueEx} hiện được dạng trắc nghiệm; ${uniqueEx-rd.questions.length} câu điền từ chưa có UI`);
  console.log(`\n## ${raw.id} (${raw.contentVersion?'v2':''})\n`+r.join('\n'));
}
